import assert from 'node:assert/strict';
import { once } from 'node:events';
import { test } from 'node:test';
import app from '../src/app.js';
import pool from '../src/config/db.js';
import { moduleTables } from '../src/controllers/healthController.js';

test('health: informa todos os módulos, schema incompleto e banco indisponível', async t => {
  const secret = process.env.JWT_SECRET;
  process.env.JWT_SECRET = 'health-test-secret';
  t.after(() => { if (secret === undefined) delete process.env.JWT_SECRET; else process.env.JWT_SECRET = secret; });
  let tables = [...new Set(Object.values(moduleTables).flat())];
  let unavailable = false;
  t.mock.method(pool, 'query', async sql => {
    assert.match(sql, /information_schema.TABLES/);
    if (unavailable) throw new Error('informação interna');
    return [tables.map(table_name => ({ table_name }))];
  });
  t.mock.method(console, 'error', () => {});
  const server = app.listen(0, '127.0.0.1');
  t.after(() => new Promise(resolve => server.close(resolve)));
  await once(server, 'listening');
  const url = `http://127.0.0.1:${server.address().port}/health`;
  const response = await fetch(url);
  assert.equal(response.status, 200);
  const body = await response.json();
  assert.equal(body.status, 'ok');
  assert.deepEqual(Object.keys(body.modules).sort(), Object.keys(moduleTables).sort());
  assert.ok(Object.values(body.modules).every(module => module.status === 'ok'));
  tables = tables.filter(table => table !== 'blocked_users');
  const incomplete = await fetch(url);
  assert.equal(incomplete.status, 503);
  const state = await incomplete.json();
  assert.equal(state.modules.settings.status, 'degraded');
  assert.deepEqual(state.modules.settings.missing_tables, ['blocked_users']);
  assert.equal(state.modules.authentication.status, 'ok');
  tables.push('blocked_users');
  delete process.env.JWT_SECRET;
  const unconfigured = await fetch(url);
  assert.equal(unconfigured.status, 503);
  const config = await unconfigured.json();
  assert.deepEqual(config.modules.authentication.missing_configuration, ['JWT_SECRET']);
  assert.equal(config.modules.feed.status, 'ok');
  process.env.JWT_SECRET = 'health-test-secret';
  unavailable = true;
  const failed = await fetch(url);
  assert.equal(failed.status, 503);
  const result = await failed.json();
  assert.equal(result.database.status, 'unavailable');
  assert.ok(Object.values(result.modules).every(module => module.status === 'unavailable'));
  assert.doesNotMatch(JSON.stringify(result), /interna/);
});
